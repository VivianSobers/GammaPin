"""Coverage of the end-of-day caches over the H1 sample: which expiries have the inputs h1_eod.py needs.

Per Nifty expiry in h1_eod.sample (nearest listed expiries in prereg.toml [h1_eod], eve cached): eve bhavcopy present
by construction, expiry-day bhavcopy present, Nifty option rows on the eve, participant OI usable for the eve
(the date rule of participant_oi.weights_for), and a T-bill rate (rates.rate_on).

Missing trading days: research has no holiday table (docs/CALENDAR.md covers Oct-Dec 2026 only), so a
weekday counts as a trading day when NSE published a participant OI or index-close file for it (both 404
on holidays). A trading day without a bhavcopy is a gap; a weekday with no file from any source is taken
as a holiday and listed separately.

Writes derived counts only (docs/COVERAGE.md by default), never raw data.
"""

from __future__ import annotations

import argparse
import datetime as dt
from collections.abc import Callable
from pathlib import Path

import polars as pl

import bhavcopy
import h1_eod
import participant_oi
import prereg
import rates
import settlements

OUT = Path(__file__).resolve().parent.parent / "docs" / "COVERAGE.md"


def file_days(cache_dir: Path, pattern: str, fmt: str) -> set[dt.date]:
    """Dates in cached file names `<prefix>_<date>.csv` (the date is the last _-separated field)."""
    return {dt.datetime.strptime(p.stem.rsplit("_", 1)[1], fmt).date() for p in Path(cache_dir).glob(pattern)}


def ok(fn: Callable, *a) -> bool:
    try:
        fn(*a)
        return True
    except LookupError:
        return False


def report(
    days: list[dt.date],
    load: Callable[[dt.date], pl.DataFrame],
    start: dt.date,
    end: dt.date,
    poi: pl.DataFrame,
    rate_df: pl.DataFrame,
    other_days: set[dt.date],
) -> dict:
    """Per-expiry rows plus missing-day lists over [min(days), max(days)]."""
    have = set(days)
    rows = []
    for e, eve in sorted(h1_eod.sample(days, load, start, end).items()):
        df = load(eve)
        rows.append({
            "expiry": e,
            "eve": eve,
            "expiry_bhavcopy": e in have,
            "contracts": df.height,
            "contracts_expiry": df.filter(pl.col("expiry") == e).height,
            "participant_oi": ok(participant_oi.latest_before, eve, poi),
            "tbill": ok(rates.rate_on, eve, rate_df),
        })
    span = participant_oi.weekdays(min(days), max(days)) if days else []
    gaps = [d for d in span if d not in have and d in other_days]
    holidays = [d for d in span if d not in have and d not in other_days]
    return {"rows": rows, "n_days": len(days), "span": (min(days, default=None), max(days, default=None)),
            "gaps": gaps, "holidays": holidays}


def markdown(rep: dict) -> str:
    rows = rep["rows"]
    yn = lambda b: "yes" if b else "**no**"  # noqa: E731
    full = sum(r["expiry_bhavcopy"] and r["participant_oi"] and r["tbill"] for r in rows)
    lines = [
        "# Bhavcopy coverage (CP-G2)",
        "",
        "Generated by `cd research && python bhav_coverage.py`. Derived counts only; the caches stay out of git.",
        "",
        f"- Bhavcopies cached: {rep['n_days']}, {rep['span'][0]} to {rep['span'][1]}",
        f"- Sample expiries (h1_eod.sample): {len(rows)}; with expiry-day bhavcopy, participant OI and T-bill: {full}",
        f"- Expiry-day bhavcopy missing: {sum(not r['expiry_bhavcopy'] for r in rows)}",
        f"- Participant OI unusable on the eve: {sum(not r['participant_oi'] for r in rows)}",
        f"- No T-bill rate before the eve: {sum(not r['tbill'] for r in rows)}",
        f"- Trading days without a bhavcopy (participant OI or index close exists): {len(rep['gaps'])}"
        + (" (" + ", ".join(d.isoformat() for d in rep["gaps"]) + ")" if rep["gaps"] else ""),
        f"- Weekdays with no file from any source (taken as NSE holidays): {len(rep['holidays'])}",
        "",
        "Contracts = Nifty option rows in the eve bhavcopy (all expiries / this expiry).",
        "",
        "| Expiry | Eve | Expiry bhavcopy | Contracts | This expiry | Participant OI | T-bill |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['expiry']} | {r['eve']} | {yn(r['expiry_bhavcopy'])} | {r['contracts']} "
            f"| {r['contracts_expiry']} | {yn(r['participant_oi'])} | {yn(r['tbill'])} |"
        )
    lines += ["", "## Holidays inferred", "", ", ".join(d.isoformat() for d in rep["holidays"]) or "none", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    days = bhavcopy.cached_days()
    other = file_days(participant_oi.CACHE_DIR, "fao_participant_oi_*.csv", "%d%m%Y") | file_days(
        settlements.CACHE_DIR, "ind_close_all_*.csv", "%d%m%Y"
    )
    rep = report(days, bhavcopy.load, *h1_eod.sample_window(prereg.load()), participant_oi.load(), rates.load(), other)
    args.out.write_text(markdown(rep), encoding="utf-8")
    print(f"{len(rep['rows'])} expiries, {len(rep['gaps'])} gaps, {len(rep['holidays'])} holidays; wrote {args.out}")


if __name__ == "__main__":
    main()
